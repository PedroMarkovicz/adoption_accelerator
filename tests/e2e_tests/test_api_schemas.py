"""
Unit tests: API schema validation.

``TestAdoptionSpeedClassEnum``, ``TestPetProfileRequest``, and
``TestTranslateRequest`` exercise the frontend-facing request schemas and
need no LLM call, so they run in the default (non-llm) test suite.

``TestAdoptionReportFromE2EOutputs`` loads the ``final_response`` section
of each e2e output JSON in ``tests/e2e_tests/outputs/`` -- a full
``AdoptionReport`` produced by a real graph run -- and asserts it
round-trips cleanly through the ``ReportStatusResponse`` API schema. This
class requires fixtures generated by a real LLM run (see
``tests/e2e_tests/run_e2e.py``), so it is marked ``@pytest.mark.llm`` and
excluded from the default suite. Regenerate the fixtures with a valid
OPENAI_API_KEY before running ``pytest tests/e2e_tests -m llm``.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from adoption_accelerator.agents.contracts import AdoptionReport
from app.api.schemas.enums import AdoptionSpeedClass
from app.api.schemas.requests import PetProfileRequest
from app.api.schemas.responses import ReportStatusResponse
from app.api.services.prediction_service import translate_request

OUTPUTS_DIR = Path(__file__).parent / "outputs"

SCENARIO_FILES = [
    "typical_dog_with_description.json",
    "typical_cat_no_description.json",
    "fully_documented_pet.json",
    "minimal_input.json",
    "high_fee_unvaccinated.json",
    "young_puppy_healthy.json",
    "senior_cat_health_issues.json",
    "multiple_pets_listing.json",
    "whitespace_only_description.json",
    "very_long_description.json",
]


def _load_final_response(scenario_file: str) -> dict:
    """Load the ``final_response`` section of an e2e output JSON.

    This is the JSON-serialized ``AdoptionReport`` (``report.model_dump(
    mode="json")``) written by ``tests/e2e_tests/runner.py``.
    """
    path = OUTPUTS_DIR / scenario_file
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data["final_response"]


def _load_report(scenario_file: str) -> AdoptionReport:
    return AdoptionReport.model_validate(_load_final_response(scenario_file))


