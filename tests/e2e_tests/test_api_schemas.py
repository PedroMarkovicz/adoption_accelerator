# AdoptionReport / ReportStatusResponse tests against real e2e outputs.
#
# These require fixtures produced by a real graph run (data_analyst,
# visual_analyst, recommendation_agent, and synthesizer all call an LLM),
# so the whole class is excluded from the default (non-llm) test suite.
# ---------------------------------------------------------------------------


class TestAdoptionReportFromE2EOutputs:
    pytestmark = pytest.mark.llm

    @pytest.mark.parametrize("scenario_file", SCENARIO_FILES)
    def test_report_is_valid_adoption_report(self, scenario_file: str):
        report = _load_report(scenario_file)
        assert isinstance(report, AdoptionReport)

    @pytest.mark.parametrize("scenario_file", SCENARIO_FILES)
    def test_predicted_class_in_valid_range(self, scenario_file: str):
        report = _load_final_response(scenario_file)
        assert report["prediction"]["predicted_class"] in range(5)

    @pytest.mark.parametrize("scenario_file", SCENARIO_FILES)
    def test_probabilities_sum_to_one(self, scenario_file: str):
        report = _load_final_response(scenario_file)
        total = sum(report["prediction"]["probabilities"].values())
        assert abs(total - 1.0) < 1e-3

    @pytest.mark.parametrize("scenario_file", SCENARIO_FILES)
    def test_narrative_is_present(self, scenario_file: str):
        report = _load_final_response(scenario_file)
        assert report["narrative"]

    @pytest.mark.parametrize("scenario_file", SCENARIO_FILES)
    def test_session_id_is_present(self, scenario_file: str):
        report = _load_final_response(scenario_file)
        assert report["metadata"]["session_id"]

    @pytest.mark.parametrize("scenario_file", SCENARIO_FILES)
    def test_recommendations_match_validated_recommendation_shape(self, scenario_file: str):
        report = _load_final_response(scenario_file)
        recommendations = report.get("recommendations")
        if not recommendations:
            pytest.skip("no recommendation evidence in this scenario's output")
        for rec in recommendations["recommendations"]:
            impact = rec["measured_impact"]
            assert impact["class_before"] in range(5)
            assert impact["class_after"] in range(5)
            assert isinstance(impact["probability_shift"], dict)

    @pytest.mark.parametrize("scenario_file", SCENARIO_FILES)
    def test_report_roundtrips_through_report_status_response(self, scenario_file: str):
        """AdoptionReport must serialize cleanly inside the API's
        ReportStatusResponse wrapper (the same shape POST /predict and its
        status poll return)."""
        report = _load_report(scenario_file)
        status = ReportStatusResponse(
            session_id=report.metadata.session_id,
            status="done",
            report=report,
            error=None,
        )
        json_str = status.model_dump_json()
        assert len(json_str) > 0
        reparsed = ReportStatusResponse.model_validate_json(json_str)
        assert reparsed.session_id == status.session_id
        assert reparsed.report.prediction.predicted_class == report.prediction.predicted_class

    def test_all_scenarios_produce_a_valid_report(self):
        passed: list[str] = []
        failed: list[tuple[str, str]] = []

        for scenario_file in SCENARIO_FILES:
            try:
                report = _load_report(scenario_file)
                assert report.prediction.predicted_class in range(5)
                assert report.narrative
                assert report.metadata.session_id
                passed.append(scenario_file)
            except Exception as exc:
                failed.append((scenario_file, str(exc)))

        assert len(failed) == 0, (
            f"Validation gate FAILED for {len(failed)}/{len(SCENARIO_FILES)} scenarios:\n"
            + "\n".join(f"  {name}: {err}" for name, err in failed)
        )
        assert len(passed) == len(SCENARIO_FILES)
